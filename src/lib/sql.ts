    text: 'CLOB', boolean: 'NUMBER(1)', bool: 'NUMBER(1)', datetime: 'TIMESTAMP',
    timestamp: 'TIMESTAMP', date: 'DATE', decimal: 'NUMBER(10,2)', float: 'BINARY_FLOAT',
